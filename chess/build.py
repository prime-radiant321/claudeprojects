#!/usr/bin/env python3
"""Build the standalone Chess with Claude site from app.html.

app.html is the same page that is published as the claude.ai artifact. This script wraps it
into a full HTML document for static hosting (Cloudflare Pages), swaps Google Fonts for the
local copies in site/fonts, and regenerates the offline service worker.

Usage:  python3 build.py        (writes site/index.html and site/sw.js)
"""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SITE = ROOT / "site"

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
{title}
<meta name="description" content="Play chess against a built-in engine from 1000 to 2100 Elo, and learn eight openings move by move with explore and practice modes.">
<meta name="theme-color" content="#E5E9E1" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#101512" media="(prefers-color-scheme: dark)">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" href="icons/icon-32.png" sizes="32x32" type="image/png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Chess">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<link rel="stylesheet" href="fonts.css">
<style>
:root { color-scheme: light; padding-top: env(safe-area-inset-top, 0px); padding-bottom: env(safe-area-inset-bottom, 0px); }
body { margin: 0; font: 14px system-ui, -apple-system, "Segoe UI", sans-serif; }
img { max-width: 100%; }
[hidden] { display: none !important; }
</style>
{style}
<script>window.CHESS_STANDALONE = true;</script>
</head>
<body>
"""

FOOT = """
<script>
if ('serviceWorker' in navigator) {
  window.addEventListener('load', () => { navigator.serviceWorker.register('sw.js').catch(() => {}); });
}
</script>
</body>
</html>
"""

SW = """// Offline support for Chess with Claude. Generated by build.py; do not edit by hand.
const CACHE = 'chess-{version}';
const ASSETS = {assets};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('chess-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // The page: try the network first so updates arrive, fall back to the cached copy offline.
    event.respondWith(
      fetch(req).then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((cache) => cache.put('index.html', copy));
        return res;
      }).catch(() => caches.match('index.html')),
    );
    return;
  }
  // Fonts, icons and the rest: cache first.
  event.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
"""


def main():
    src = (ROOT / "app.html").read_text(encoding="utf-8")

    title = re.search(r"<title>.*?</title>", src).group(0)
    src = src.replace(title, "", 1)
    src = re.sub(r'<meta name="claude:viewport-fit-sides"[^>]*>\n?', "", src)
    # Google Fonts -> local fonts.css (linked in the head).
    src = re.sub(r'<link rel="preconnect"[^>]*>\n?', "", src)
    src = re.sub(r'<link rel="stylesheet" href="https://fonts\.googleapis\.com[^>]*>\n?', "", src)
    if "fonts.googleapis.com" in src:
        raise SystemExit("app.html still references Google Fonts; update build.py")
    style = re.search(r"<style>[\s\S]*?</style>", src).group(0)
    src = src.replace(style, "", 1)

    page = HEAD.replace("{title}", title).replace("{style}", style) + src.strip() + "\n" + FOOT
    (SITE / "index.html").write_text(page, encoding="utf-8")

    assets = ["./", "index.html", "fonts.css", "manifest.webmanifest"]
    assets += sorted("icons/" + p.name for p in (SITE / "icons").glob("*.png"))
    assets += sorted("fonts/" + p.name for p in (SITE / "fonts").glob("*.woff2"))
    digest = hashlib.sha256()
    for a in assets[1:]:
        digest.update((SITE / a).read_bytes())
    version = digest.hexdigest()[:10]
    sw = SW.replace("{version}", version).replace("{assets}", json.dumps(assets, indent=2))
    (SITE / "sw.js").write_text(sw, encoding="utf-8")
    print(f"Built site/index.html ({len(page) // 1024} KB) and site/sw.js (cache chess-{version}, {len(assets)} files)")


if __name__ == "__main__":
    main()
